import assert from "node:assert/strict";
import { turbulenceIntensity as at } from "../web/turbulence_profile.mjs";
assert.equal(at(2000,1,1,1000,1,true),2);
assert.equal(at(2000,1,1,1000,.1,true),.2);
assert.equal(at(2000,1,1,1000,.1,false),.1);
assert.equal(at(500,1,1,1000,1,false),0);
assert.equal(at(500,1,1,1000,1,true),.5);
assert.equal(at(15000,0,1,40,2,true),0);
assert.equal(at(2000,4,1,1000,0,true),0);
assert.ok(Number.isFinite(at(Infinity,NaN,NaN,NaN,NaN,true)));
